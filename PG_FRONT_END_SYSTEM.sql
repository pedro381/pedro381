    PROCEDURE SP_OBTER_REMARKETING_LISTA_VEICULOS(
        P_CD_DN           IN CADPD_OWN.FES_REMARKETING_ESTOQUE.CD_DN%TYPE,
        P_NM_CIDADE       IN CADPD_OWN.FES_REMARKETING_ESTOQUE.NM_CIDADE%TYPE DEFAULT NULL,
        P_NM_UF           IN CADPD_OWN.FES_REMARKETING_ESTOQUE.NM_UF%TYPE DEFAULT NULL,
        P_NM_MODELO          IN VARCHAR2 DEFAULT NULL,
        P_NM_PLACA           IN VARCHAR2 DEFAULT NULL,
        P_FL_STATUS       IN VARCHAR2 DEFAULT 'T',
		P_QT_ITENS_PAGINA IN OUT NUMBER,
        P_NR_PAGINA       IN OUT NUMBER,
        P_RETORNO         OUT SYS_REFCURSOR
    ) IS
        P_CNPJ_PARAMETRO VARCHAR2(20);
		V_OFFSET NUMBER;
    BEGIN

    SELECT FRP.NR_CNPJ INTO P_CNPJ_PARAMETRO
      FROM CADPD_OWN.FES_REMARKETING_PARAMETROS FRP
     WHERE FRP.CD_DN = P_CD_DN;
	 
	 IF P_QT_ITENS_PAGINA IS NULL OR P_QT_ITENS_PAGINA < 1 THEN
		P_QT_ITENS_PAGINA := 20;
	 END IF;

	 IF P_NR_PAGINA IS NULL OR P_NR_PAGINA < 1 THEN
		V_OFFSET := 1;
	 ELSE
		V_OFFSET := (P_NR_PAGINA - 1) * P_QT_ITENS_PAGINA;
	 END IF;

        OPEN P_RETORNO FOR
            SELECT FRE.ID, FRE.ID_CONFIG, 
                   NVL(FRE.NR_CNPJ,P_CNPJ_PARAMETRO) NR_CNPJ,
                   FRE.NM_PLACA, FRE.NM_MODELO, FRE.VL_FIPE, FRE.NR_HODOMETRO,
                   FRE.NM_COR, FRE.NR_ANO_MODELO, FRE.DS_LAUDO_CAUTELAR_LINK, FRE.VL_VENDA, FRE.NM_CIDADE,
                   FRE.NM_UF, FRE.FL_RESERVA, FRE.CD_DN, FRE.DT_COMPRA, FRE.TP_FATURAMENTO,
                   CASE WHEN FRE.FL_RESERVA = 'N' THEN 'D'
                        WHEN FRE.FL_RESERVA = 'S' THEN 
                                    CASE WHEN FRE.CD_DN <> P_CD_DN THEN 'O' ELSE 'R' END
                   END AS FL_STATUS, NM_USER_RESERVA,
				   
				   COUNT(*) OVER () AS QT_REGISTROS_TOTAIS,
				   CEIL(COUNT(*) OVER () / P_QT_ITENS_PAGINA) AS NR_TOTAL_PAGINAS
				   
              FROM CADPD_OWN.FES_REMARKETING_ESTOQUE FRE
             WHERE 
				(
					(P_NM_UF IS NULL
						OR TRIM(P_NM_UF) = '')
						OR UPPER( TRIM(NM_UF)) IN (
							SELECT UPPER(TRIM(REGEXP_SUBSTR(UPPER(TRIM(P_NM_UF)), '[^,]+', 1, LEVEL)))
							FROM DUAL
							CONNECT BY REGEXP_SUBSTR(P_NM_UF, '[^,]+', 1, LEVEL) IS NOT NULL
							)
				)
                AND 
				(
					(P_NM_CIDADE IS NULL
						OR TRIM(P_NM_CIDADE) = '')
						OR UPPER(TRIM(NM_CIDADE)) IN (
							SELECT UPPER(TRIM(REGEXP_SUBSTR(UPPER(TRIM(P_NM_CIDADE)), '[^,]+', 1, LEVEL)))
							FROM DUAL
							CONNECT BY REGEXP_SUBSTR(P_NM_CIDADE, '[^,]+', 1, LEVEL) IS NOT NULL
							)
				)
                AND 
				(
                     (P_NM_MODELO IS NULL
						OR TRIM(P_NM_MODELO) = '')
						OR UPPER(TRIM(NM_MODELO)) IN (
							SELECT UPPER(TRIM(REGEXP_SUBSTR(UPPER(TRIM(P_NM_MODELO)), '[^,]+', 1, LEVEL)))
							FROM DUAL
							CONNECT BY REGEXP_SUBSTR(P_NM_MODELO, '[^,]+', 1, LEVEL) IS NOT NULL
							)
                )
				AND
				(
					(P_NM_PLACA IS NULL
						OR TRIM(P_NM_PLACA) = '')
						OR UPPER(TRIM(NM_PLACA)) IN (
							SELECT UPPER(TRIM(REGEXP_SUBSTR(UPPER(TRIM(P_NM_PLACA)), '[^,]+', 1, LEVEL)))
							FROM DUAL
							CONNECT BY REGEXP_SUBSTR(P_NM_PLACA, '[^,]+', 1, LEVEL) IS NOT NULL
							)
				)
                AND ((P_FL_STATUS = 'D' AND FRE.CD_DN Is Null)
                    OR 
                    (P_FL_STATUS = 'R' AND FRE.CD_DN = P_CD_DN)
                    OR
                    P_FL_STATUS = 'T'
                   )
               ORDER BY FRE.ID
				OFFSET V_OFFSET ROWS
				FETCH NEXT P_QT_ITENS_PAGINA ROWS ONLY;
	EXCEPTION
	  WHEN OTHERS THEN
				 RAISE_APPLICATION_ERROR (-20001,
				 'PROBLEMAS AO SP REALIZAR LISTA CARROS.'
				 || CHR (13)
				 || 'SQLERRM: '
				 || SQLERRM
				 || CHR (13)
				 || 'ERROR_STACK: '
				 || DBMS_UTILITY.FORMAT_ERROR_STACK
				 || CHR (13)
				 || 'ERROR_BACKTRACE: '
				 || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
    END SP_OBTER_REMARKETING_LISTA_VEICULOS;
	
