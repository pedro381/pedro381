PROCEDURE SP_MANTER_REMARKETING_PARAMETROS_CALC(
        P_ID                          IN OUT CADPD_OWN.FES_REMARKETING_PARAMETROS_CALC.ID%TYPE,
        P_NM_GRUPO_DN                 IN     CADPD_OWN.FES_REMARKETING_PARAMETROS_CALC.NM_GRUPO_DN%TYPE,
        P_DS_GRUPO_DN                 IN     CADPD_OWN.FES_REMARKETING_PARAMETROS_CALC.DS_GRUPO_DN%TYPE,
        P_QT_LIMITE_DESCONTO          IN     CADPD_OWN.FES_REMARKETING_PARAMETROS_CALC.QT_LIMITE_DESCONTO%TYPE,
        P_VL_LIMITE_DESCONTO          IN     CADPD_OWN.FES_REMARKETING_PARAMETROS_CALC.VL_LIMITE_DESCONTO%TYPE,
        P_QT_DESCONTO_VEICULO_B       IN     CADPD_OWN.FES_REMARKETING_PARAMETROS_CALC.QT_DESCONTO_VEICULO_B%TYPE,
        P_QT_DESCONTO_VEICULO_C       IN     CADPD_OWN.FES_REMARKETING_PARAMETROS_CALC.QT_DESCONTO_VEICULO_C%TYPE,
        P_RETORNO                     OUT    NUMBER
    ) IS
    BEGIN
        IF P_ID IS NULL OR P_ID = 0 THEN
            P_ID := CADPD_OWN.FES_REMARKETING_PARAMETROS_CALC_SEQ.NEXTVAL;
        END IF;

        P_RETORNO := P_ID;

        MERGE INTO CADPD_OWN.FES_REMARKETING_PARAMETROS_CALC t
        USING (SELECT P_ID AS ID FROM DUAL) s
        ON (t.ID = s.ID)
        WHEN MATCHED THEN
            UPDATE SET  NM_GRUPO_DN = P_NM_GRUPO_DN,
                        DS_GRUPO_DN = P_DS_GRUPO_DN,
                        QT_LIMITE_DESCONTO = P_QT_LIMITE_DESCONTO,
                        VL_LIMITE_DESCONTO = P_VL_LIMITE_DESCONTO,
                        QT_DESCONTO_VEICULO_B = P_QT_DESCONTO_VEICULO_B,
                        QT_DESCONTO_VEICULO_C = P_QT_DESCONTO_VEICULO_C
        WHEN NOT MATCHED THEN
            INSERT (ID,
                    NM_GRUPO_DN,
                    DS_GRUPO_DN,
                    QT_LIMITE_DESCONTO,
                    VL_LIMITE_DESCONTO,
                    QT_DESCONTO_VEICULO_B,
                    QT_DESCONTO_VEICULO_C)
            VALUES (P_ID,
                    P_NM_GRUPO_DN,
                    P_DS_GRUPO_DN,
                    P_QT_LIMITE_DESCONTO,
                    P_VL_LIMITE_DESCONTO,
                    P_QT_DESCONTO_VEICULO_B,
                    P_QT_DESCONTO_VEICULO_C);

    EXCEPTION
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR (-20001,
                'PROBLEMAS AO SP MANTER REMARKETING PARAMETROS CALC.'
                || CHR (13)
                || 'SQLERRM: '
                || SQLERRM
                || CHR (13)
                || 'ERROR_STACK: '
                || DBMS_UTILITY.FORMAT_ERROR_STACK
                || CHR (13)
                || 'ERROR_BACKTRACE: '
                || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
END SP_MANTER_REMARKETING_PARAMETROS_CALC;

